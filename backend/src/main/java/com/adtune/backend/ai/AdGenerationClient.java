package com.adtune.backend.ai;

/**
 * Общий интерфейс взаимодействия с AI-моделью, готовящей материалы объявления.
 *
 * <p>Имплементация выбирается свойством {@code adtune.ai.provider}. Чтобы перейти
 * на другого провайдера (другая нейронка, self-hosted шлюз и т.п.), пишется новая
 * имплементация этого интерфейса — остальной код от провайдера не зависит.
 */
public interface AdGenerationClient {

  /**
   * Готовит материалы объявления по параметрам квартиры, описаниям фотографий
   * и настройкам выбранных площадок.
   *
   * @throws AiClientException если модель не настроена, недоступна или вернула
   *     нечитаемый ответ
   */
  AdGenerationResult generate(AdGenerationRequest request);
}
