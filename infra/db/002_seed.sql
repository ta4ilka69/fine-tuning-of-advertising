BEGIN;

CREATE TEMP TABLE seed_channel ON COMMIT DROP AS
SELECT uuidv7() AS channel_id, uuidv7() AS version_id, seed.*
FROM (VALUES
    (
        'Авито',
        'Подробное объявление с заголовком для Авито.',
        'Напиши объявление о недвижимости для Авито. Пиши по делу, без капслока и восклицательных знаков, не выдумывай факты, которых нет в данных объекта.',
        '["Заголовок содержит тип объекта и площадь", "Указаны цена и условия сделки", "Описано расположение и транспорт", "Нет капслока и лишних восклицательных знаков", "Нет контактов и ссылок в тексте"]'::jsonb,
        50,
        7500
    ),
    (
        'ЦИАН',
        'Структурированное объявление для ЦИАН.',
        'Напиши объявление о недвижимости для ЦИАН. Начни с главных характеристик объекта, затем опиши состояние, дом и окружение. Не выдумывай факты, которых нет в данных объекта.',
        '["Первый абзац содержит главные характеристики", "Указаны цена и условия сделки", "Описаны дом и инфраструктура", "Нет контактов и ссылок в тексте"]'::jsonb,
        100,
        6000
    ),
    (
        'Telegram',
        'Короткий пост для Telegram-канала.',
        'Напиши короткий пост о недвижимости для Telegram-канала. Первая строка — суть предложения, дальше короткие абзацы. Не выдумывай факты, которых нет в данных объекта.',
        '["Первая строка передаёт суть предложения", "Указана цена", "Текст разбит на короткие абзацы"]'::jsonb,
        NULL,
        1024
    )
) AS seed (name, description, instruction, checklist, title_limit, text_limit);

INSERT INTO channel (id, name, description, current_version_id)
SELECT channel_id, name, description, version_id FROM seed_channel;

INSERT INTO channel_version (id, channel_id, number, instruction, checklist, title_limit, text_limit)
SELECT version_id, channel_id, 1, instruction, checklist, title_limit, text_limit FROM seed_channel;

COMMIT;
